#!/usr/bin/env python3
"""Generate WotLK level overrides and native starter sites from reviewed world snapshots.
No database access. XYZ comes verbatim from beginner-sites.json creature spawn evidence.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def generate():
    levels = json.loads((ROOT / 'tools/site-level-overrides.json').read_text())
    beginners = json.loads((ROOT / 'tools/beginner-sites.json').read_text())['sites']
    out = ['-- Generated by tools/build_site_access.py; do not edit by hand.',
           '-- Provisional placements from actual WotLK creature spawn XYZ; client paths still require testing.',
           'CREATE TABLE IF NOT EXISTS `mod_archaeology_site_access` (\n'
           '  `site` SMALLINT UNSIGNED NOT NULL,\n'
           '  `team` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT \'0 both, 1 Alliance, 2 Horde\',\n'
           '  `starter_zone` SMALLINT UNSIGNED NOT NULL DEFAULT 0,\n'
           '  PRIMARY KEY (`site`)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;']
    for sid, data in sorted(levels.items(), key=lambda v:int(v[0])):
        out.append(f"UPDATE `mod_archaeology_site` SET `min_level` = {data['min_level']} WHERE `id` = {sid};")
    for site in beginners:
        sid=site['id']; name=site['name'].replace("'", "''")
        out.append(f"INSERT INTO `mod_archaeology_site` (`id`, `map`, `race`, `name`, `min_skill`, `min_level`, `enabled`) VALUES ({sid}, {site['map']}, {site['race']}, '{name}', 0, 1, {site['enabled']}) ON DUPLICATE KEY UPDATE `min_level` = VALUES(`min_level`);")
        out.append(f"REPLACE INTO `mod_archaeology_site_access` (`site`, `team`, `starter_zone`) VALUES ({sid}, {site['team']}, {site['zone']});")
        xmin,xmax,ymin,ymax=site['bounds']
        out.append(f'DELETE FROM `mod_archaeology_site_point` WHERE `site` = {sid};')
        for i,(x,y) in enumerate(((xmin,ymin),(xmax,ymin),(xmax,ymax),(xmin,ymax))):
            out.append(f'INSERT INTO `mod_archaeology_site_point` (`site`, `idx`, `x`, `y`) VALUES ({sid}, {i}, {x:.6f}, {y:.6f});')
        out.append(f'DELETE FROM `mod_archaeology_site_spawn` WHERE `site` = {sid};')
        for i,p in enumerate(site['points']):
            out.append(f"INSERT INTO `mod_archaeology_site_spawn` (`site`, `idx`, `x`, `y`, `z`) VALUES ({sid}, {i}, {p['x']:.6f}, {p['y']:.6f}, {p['z']:.6f});")
    return '\n'.join(out)+'\n'

if __name__ == '__main__':
    (ROOT/'data/sql/db-world/mod_archaeology_world_zz_access.sql').write_text(generate())
