#!/usr/bin/env python3
"""Generate functional rare reward SQL; no network or client is needed.

DBC rows are generated from the same catalog by reward_patch.py. Update
rare-rewards.json, run this tool, then rebuild the realm spell/item patch.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'data/rare-rewards.json'
OUT = ROOT / 'data/sql/db-world/mod_archaeology_world_z_rewards.sql'


def quote(s):
    return "'" + s.replace("'", "''") + "'"


def generate(data):
    lines = ['-- Generated by tools/build_rewards.py from data/rare-rewards.json.',
             '-- Rebuild the matching client patch and module before deploying this SQL.',
             '-- Retail Collection/Library supply Fossilized Hatchling and Fossilized Raptor.']
    for c in data['collectibles']:
        lines += [f"UPDATE `item_template` SET `spellid_1`=55884, `spelltrigger_1`=0, `spellcharges_1`=-1, "
                  f"`spellid_2`={c['spell']}, `spelltrigger_2`=6, `spellcharges_2`=0, "
                  f"`RequiredSkill`={762 if c['kind']=='mount' else 0}, `RequiredSkillRank`={75 if c['kind']=='mount' else 0}, "
                  f"`ScriptName`='item_archaeology_companion' WHERE `entry`={c['item']};"]
    for t in data['toys']:
        lines += [f"UPDATE `item_template` SET `spellid_1`={t['spell']}, `spelltrigger_1`=0, `spellcharges_1`=0, "
                  f"`spellid_2`=0, `spelltrigger_2`=0, `spellcharges_2`=0, `ScriptName`='', "
                  f"`description`={quote(t['text'])} WHERE `entry`={t['item']};"]
    for g in data['gear']:
        values = dict(Class=g['cls'],subclass=g['sub'],InventoryType=g['slot'],Material=g['material'],
                      sheath=g['sheath'],displayid=g['display'],ItemLevel=g['ilvl'],RequiredLevel=g['level'],
                      Quality=g['quality'],armor=g['armor'],block=g['block'],
                      dmg_min1=g['damage'][0],dmg_max1=g['damage'][1],delay=g['delay'],
                      MaxDurability=0,spellid_1=g.get('use',0),spelltrigger_1=0,
                      spellcharges_1=0,spellid_2=0,spelltrigger_2=0,spellcharges_2=0)
        for i in range(1,11):
            stat, val = g['stats'][i-1] if i <= len(g['stats']) else (0,0)
            values[f'stat_type{i}'],values[f'stat_value{i}']=stat,val
        values.update(socketColor_1=0,socketColor_2=0,socketColor_3=0,socketContent_1=0,socketContent_2=0,socketContent_3=0,socketBonus=0)
        lines += ['UPDATE `item_template` SET '+', '.join(f'`{k}`={v}' for k,v in values.items())+
                  f", `ScriptName`='' WHERE `entry`={g['item']};"]
        lines += [f"DELETE FROM `item_dbc` WHERE `ID`={g['item']};",
                  f"INSERT INTO `item_dbc` VALUES ({g['item']},{g['cls']},{g['sub']},-1,{g['material']},{g['display']},{g['slot']},{g['sheath']});"]
    lines += ['DELETE FROM `creature_template_model` WHERE `CreatureID` BETWEEN 9503600 AND 9503613;',
              'DELETE FROM `creature_template` WHERE `entry` BETWEEN 9503600 AND 9503613;']
    actors=[(9503603,'Highborne Reflection',53,1.0),(9503604,'Ancient Druid Statue',1285,1.0),
            (9503605,'Ancient Priest Statue',1543,1.0),(9503606,'Mountain King',1277,1.0),
            (9503607,'Naaru Apparition',17065,0.35),(9503610,'Spectral Innkeeper',1286,1.0),
            (9503611,'Ancient Faceless One',27849,1.0),(9503612,'Ancient Naga',17403,1.0),
            (9503613,'Ancient Wisp',1825,1.0)]
    actors += [(c['creature'],c['name'],c['model'],c['scale']) for c in data['collectibles'] if not c.get('external')]
    for entry,name,model,scale in actors:
        # Nonattackable, not selectable, pacified; no loot, spells or combat AI.
        flags=768 if entry <= 9503602 else 33686274
        lines += [f"INSERT INTO `creature_template` (`entry`,`name`,`minlevel`,`maxlevel`,`faction`,`unit_flags`,`type`,`flags_extra`,`AIName`) "
                  f"VALUES ({entry},{quote(name)},1,1,188,{flags},12,2,'NullCreatureAI');",
                  f"INSERT INTO `creature_template_model` (`CreatureID`,`Idx`,`CreatureDisplayID`,`DisplayScale`,`Probability`) "
                  f"VALUES ({entry},0,{model},{scale},1);"]
    lines += ["DELETE FROM `gameobject_template` WHERE `entry`=9503530;",
              "INSERT INTO `gameobject_template` (`entry`,`type`,`displayId`,`name`,`size`,`flags`) VALUES (9503530,5,7217,'Haunted War Drum',1,16);",
              "DELETE FROM `spell_script_names` WHERE `ScriptName` IN ('spell_archaeology_reward','spell_archaeology_innkeepers_daughter');"]
    for t in data['toys']:
        if not t.get('external'):
            lines += [f"INSERT INTO `spell_script_names` VALUES ({t['spell']},'spell_archaeology_reward');"]
    lines += ["INSERT INTO `spell_script_names` VALUES (8690,'spell_archaeology_innkeepers_daughter');",
              "CREATE TABLE IF NOT EXISTS `mod_forever_journal_toy` (`ItemID` INT UNSIGNED NOT NULL, `Comment` VARCHAR(100) NOT NULL DEFAULT '', PRIMARY KEY (`ItemID`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"]
    lines += [f"REPLACE INTO `mod_forever_journal_toy` (`ItemID`,`Comment`) VALUES ({t['item']},{quote(t['name'])});" for t in data['toys']]
    lines += ["CREATE TABLE IF NOT EXISTS `mod_forever_journal_collection_note` (`Kind` CHAR(1) NOT NULL, `ID` INT UNSIGNED NOT NULL, `Sort` TINYINT UNSIGNED NOT NULL DEFAULT 0, `Note` VARCHAR(200) NOT NULL, PRIMARY KEY (`Kind`,`ID`,`Sort`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"]
    for c in data['toys'] + data['collectibles']:
        kind = 'T' if c in data['toys'] else 'M' if c['kind']=='mount' else 'P'
        entry = c['item'] if kind=='T' else c['spell']
        lines += [f"REPLACE INTO `mod_forever_journal_collection_note` (`Kind`,`ID`,`Sort`,`Note`) VALUES ({quote(kind)},{entry},90,{quote('Archaeology: solve '+c['name']+'.')});"]
    return '\n'.join(lines)+'\n'


def main():
    data=json.loads(CATALOG.read_text())
    OUT.write_text(generate(data))


if __name__=='__main__':
    main()
