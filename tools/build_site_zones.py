#!/usr/bin/env python3
"""The zone each dig site lies in, for the zone rotation (a dug-out site waits for its zone).

    build_site_zones.py            tools/site-zones.json -> data/sql/db-world/mod_archaeology_world_zz_zones.sql
    build_site_zones.py --from-db  re-vote tools/site-zones.json from a world DB, then write the SQL

The vote: the zoneId of the creature and gameobject spawns inside the site's outline (the core's
Calculate.Creature.Zone.Area.Data fills those from the map), the most common one wins. A site with
no zoned spawn inside looks 150 yards around its outline. --from-db reads AC_DB_HOST/AC_DB_PORT/
AC_DB_USER/AC_DB_PASS/AC_DB_WORLD from the environment and needs pymysql.
"""
import collections
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ZONES = ROOT / 'tools/site-zones.json'
SQL = ROOT / 'data/sql/db-world/mod_archaeology_world_zz_zones.sql'
MARGIN = 150.0


def inside(poly, x, y):
    hit = False
    j = len(poly) - 1
    for i, (xi, yi) in enumerate(poly):
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def vote(cur):
    cur.execute('SELECT `id`, `map` FROM `mod_archaeology_site`')
    sites = cur.fetchall()
    cur.execute('SELECT `site`, `x`, `y` FROM `mod_archaeology_site_point` ORDER BY `site`, `idx`')
    polys = collections.defaultdict(list)
    for site, x, y in cur.fetchall():
        polys[site].append((float(x), float(y)))
    spawns = collections.defaultdict(list)
    for table in ('creature', 'gameobject'):
        cur.execute(f'SELECT `map`, `position_x`, `position_y`, `zoneId` FROM `{table}` WHERE `zoneId` <> 0')
        for m, x, y, zone in cur.fetchall():
            spawns[m].append((float(x), float(y), int(zone)))
    zones = {}
    for site, m in sites:
        poly = polys.get(site)
        if not poly or len(poly) < 3:
            continue
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        votes = collections.Counter(z for x, y, z in spawns[m]
                                    if min(xs) <= x <= max(xs) and min(ys) <= y <= max(ys) and inside(poly, x, y))
        if not votes:
            votes = collections.Counter(z for x, y, z in spawns[m]
                                        if min(xs) - MARGIN <= x <= max(xs) + MARGIN and min(ys) - MARGIN <= y <= max(ys) + MARGIN)
        if votes:
            zones[str(site)] = max(votes.items(), key=lambda kv: (kv[1], -kv[0]))[0]
    return zones


def generate(zones):
    out = ['-- Generated by tools/build_site_zones.py from tools/site-zones.json; do not edit by hand.',
           '-- The zone of each dig site: a dug-out site waits until the sites you hold in its zone are dug out too.',
           'CREATE TABLE IF NOT EXISTS `mod_archaeology_site_zone` (\n'
           '  `site` SMALLINT UNSIGNED NOT NULL,\n'
           '  `zone` SMALLINT UNSIGNED NOT NULL,\n'
           '  PRIMARY KEY (`site`)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;',
           'DELETE FROM `mod_archaeology_site_zone`;']
    rows = [f'({site}, {zone})' for site, zone in sorted(((int(s), z) for s, z in zones.items()))]
    out.append('INSERT INTO `mod_archaeology_site_zone` (`site`, `zone`) VALUES\n' + ',\n'.join(rows) + ';')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    if '--from-db' in sys.argv[1:]:
        import pymysql
        db = pymysql.connect(host=os.environ.get('AC_DB_HOST', '127.0.0.1'), port=int(os.environ.get('AC_DB_PORT', '3306')),
                             user=os.environ['AC_DB_USER'], password=os.environ['AC_DB_PASS'],
                             database=os.environ.get('AC_DB_WORLD', 'acore_world'))
        ZONES.write_text(json.dumps(vote(db.cursor()), indent=1, sort_keys=True) + '\n')
    SQL.write_text(generate(json.loads(ZONES.read_text())))
